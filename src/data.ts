/** Compute the final unit price for a bean customization from a 125g base price. */
export function beanUnitPrice(basePrice: number, custom: BeanCustomization): number {
  const mult = WEIGHT_OPTIONS.find((w) => w.id === custom.weight)?.multiplier ?? 1;
  const addOn = SPICE_OPTIONS.find((s) => s.id === custom.spice)?.addOn ?? 0;
  return basePrice * mult + addOn;
}

/** Compute the final unit price for a drink customization. */
export function drinkUnitPrice(product: Product, custom: DrinkCustomization): number {
  if (custom.size === 'double' && product.hasDouble && product.doublePrice) return product.doublePrice;
  return product.price;
}

